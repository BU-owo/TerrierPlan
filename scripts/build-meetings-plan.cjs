// build-meetings-plan.cjs
// Offline: reads the Spring 2027 schedule CSV and writes the `meetings` plan
// that backfill-meetings.cjs applies, plus a human-readable report. Touches
// nothing but the two output files; no Firestore, no credentials.
//
// Usage:
//   node scripts/build-meetings-plan.cjs
//
// Writes ../TerrierPlan-out/audit/meetings-plan.json and meetings-plan.md.
//
// Requires: csv-parse

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');
const M = require('./lib/meetings.cjs');

const TERM = '2271';
const CSV_PATH = path.join(__dirname, '..', 'scheduleclasses', 'schedule_with_types_spring2027.csv');
const OUT_DIR = path.join(__dirname, '..', '..', 'TerrierPlan-out', 'audit');
const PLAN_PATH = path.join(OUT_DIR, 'meetings-plan.json');
const REPORT_PATH = path.join(OUT_DIR, 'meetings-plan.md');

// Class Nbrs already patched live (scripts/patch-meeting-rows.cjs on origin/meeting-patch):
// their top-level fields hold the pickPrimaryMeeting row, not the first CSV row.
const ALLOWLIST = new Set([
  '3771', '16920', '16921', '4400', '4463', '11469', '4365', '4391', '7614',
  '4923', '4363', '8861', '8862', '8901', '9999', '10000', '10001', '10002',
  '10003', '10712', '11232', '14281',
]);

// Course keys called out in the report.
const AMBIGUOUS = [
  { courseKey: 'ENGEK125', sections: ['A1', 'A2', 'A3'], why: 'Fri 4:30-6:15 PM block is an exam (confirmed on MyBU), forced by override; MoWe row stays class' },
  { courseKey: 'CASBI576', sections: ['A1'], why: 'Wed 2:30 pm pattern overlaps the MW lecture; could be a lab/discussion or a duplicate' },
];

function brief(m) {
  return `${m.daysOfWeek} ${m.startTime}–${m.endTime}${m.facilId === 'NO ROOM' ? ' [NO ROOM]' : ''} (${m.kind})`;
}

function main() {
  const rows = parse(fs.readFileSync(CSV_PATH, 'utf8'), { columns: true, skip_empty_lines: true });
  const sections = M.groupSections(rows, TERM);
  const noRoom = M.noRoomPatternsByCourse(sections);

  const plan = [];
  const excludedAllowlist = [];
  const mismatches = [];
  const collisions = [];
  let inScopeByMulti = 0;

  for (const section of sections.values()) {
    const allowlisted = ALLOWLIST.has(section.classNbr);
    if (!M.inMeetingsScope(section)) {
      if (allowlisted) excludedAllowlist.push(section.label);
      continue;
    }
    const built = M.buildMeetings(section, {
      noRoomPatterns: noRoom.get(section.courseKey),
      storedPick: allowlisted,
      notesExams: true,
    });
    const multi = built.patternCount >= 2;
    if (!multi && !allowlisted) continue;
    if (multi) inScopeByMulti++;
    if (built.meetings.length === 0) continue;

    plan.push({
      classNbr: section.classNbr,
      docId: section.docId,
      courseKey: section.courseKey,
      meetings: built.meetings,
      _label: section.label,
      _allowlisted: allowlisted,
      _stored: built.stored,
    });
    if (built.collisions) collisions.push(`${section.label} (${built.collisions})`);

    const first = built.meetings[0];
    if (!M.sameFields(first, built.stored)) {
      mismatches.push({ label: section.label, docId: section.docId, stored: built.stored, first, allowlisted });
    }
  }

  plan.sort((a, b) => a.courseKey.localeCompare(b.courseKey) || a.classNbr.localeCompare(b.classNbr, 'en', { numeric: true }));

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const planOut = plan.map(({ classNbr, docId, courseKey, meetings }) => ({ classNbr, docId, courseKey, meetings }));
  fs.writeFileSync(PLAN_PATH, JSON.stringify(planOut, null, 2) + '\n');

  // ── report ──
  const kindCount = { class: 0, exam: 0 };
  const perCourse = new Map();
  for (const p of plan) {
    const c = perCourse.get(p.courseKey) || { sections: 0, class: 0, exam: 0 };
    c.sections++;
    for (const m of p.meetings) {
      kindCount[m.kind]++;
      c[m.kind]++;
    }
    perCourse.set(p.courseKey, c);
  }
  const withExam = plan.filter((p) => p.meetings.some((m) => m.kind === 'exam')).length;
  const examFirst = plan.filter((p) => p.meetings[0].kind === 'exam');

  const L = [];
  L.push('# Meetings plan (Spring 2027, term 2271)', '');
  L.push(`Generated by scripts/build-meetings-plan.cjs from ${path.basename(CSV_PATH)}. Offline; nothing written to Firestore.`, '');
  L.push('## Counts', '');
  L.push(`- Sections in plan: ${plan.length} (${inScopeByMulti} with 2+ recurring patterns, ${plan.filter((p) => p._allowlisted).length} allowlisted)`);
  L.push(`- Meetings: ${kindCount.class + kindCount.exam} total — ${kindCount.class} class, ${kindCount.exam} exam`);
  L.push(`- Sections with at least one exam meeting: ${withExam}`);
  L.push(`- Sections whose meetings[0] is an exam: ${examFirst.length}`);
  L.push(`- Courses: ${perCourse.size}`);
  if (excludedAllowlist.length) L.push(`- Allowlisted but excluded by scope (OTPMS/MED/LAW/non-undergrad): ${excludedAllowlist.join(', ')}`);
  if (collisions.length) L.push(`- Same days+start+end with different rooms/dates (kept the longest span): ${collisions.join(', ')}`);
  L.push('');

  L.push('## Per-course totals', '', '| Course | Sections | Class meetings | Exam meetings |', '|---|---|---|---|');
  for (const [key, c] of [...perCourse].sort((a, b) => a[0].localeCompare(b[0]))) {
    L.push(`| ${key} | ${c.sections} | ${c.class} | ${c.exam} |`);
  }
  L.push('');

  const qst = plan.filter((p) => p.courseKey === 'QSTSM131');
  L.push(`## QST SM 131 (${qst.length} sections; each should have 2 class meetings)`, '', '| Class Nbr | Section | Meetings | Class | OK |', '|---|---|---|---|---|');
  for (const p of qst) {
    const nClass = p.meetings.filter((m) => m.kind === 'class').length;
    L.push(`| ${p.classNbr} | ${p._label.split(' ').pop()} | ${p.meetings.map(brief).join(' + ')} | ${nClass} | ${nClass === 2 && p.meetings.length === 2 ? 'yes' : 'NO'} |`);
  }
  L.push('');

  L.push('## The 22 allowlisted Class Nbrs (already patched live)', '', '| Class Nbr | Section | In plan | meetings (primary first) |', '|---|---|---|---|');
  for (const nbr of ALLOWLIST) {
    const p = plan.find((x) => x.classNbr === nbr);
    const label = p ? p._label : sections.get(`${TERM}_${nbr}`)?.label || '?';
    L.push(`| ${nbr} | ${label} | ${p ? 'yes' : 'no'} | ${p ? p.meetings.map(brief).join(' + ') : ''} |`);
  }
  L.push('');

  L.push('## Ambiguous', '');
  for (const a of AMBIGUOUS) {
    L.push(`- ${a.courseKey} (${a.why})`);
    for (const p of plan.filter((x) => x.courseKey === a.courseKey)) {
      const sec = p._label.split(' ').pop();
      if (a.sections.includes(sec)) L.push(`    - ${p._label} (${p.classNbr}): ${p.meetings.map(brief).join(' + ')}`);
    }
  }
  L.push('');

  L.push('## meetings[0] vs. current top-level fields', '');
  L.push('Current top-level = first CSV row (today\'s importer), or the pickPrimaryMeeting row for the allowlisted 22. The backfill skips every section listed here.', '');
  if (!mismatches.length) L.push('None.');
  for (const x of mismatches) {
    L.push(`- ${x.label} (${x.docId})${x.allowlisted ? ' [allowlisted]' : ''}`);
    L.push(`    - top-level: ${M.describeFields(x.stored)}`);
    L.push(`    - meetings[0]: ${M.describeFields(x.first)} (${x.first.kind})`);
  }
  L.push('');

  L.push('## Change for import-sections.cjs (not made yet)', '');
  L.push('Not edited. To write `meetings` on future imports:', '');
  L.push("1. `const M = require('./lib/meetings.cjs');` near the top (and drop the copied pickPrimaryMeeting logic from the importer if the meeting-patch branch lands, so there is one copy).");
  L.push('2. While looping rows, also push every row onto a per-key list (the importer already groups by `term_classNbr`).');
  L.push('3. After the loop: `const groups = M.groupSections(rows, term)` (or per term), `const noRoom = M.noRoomPatternsByCourse(groups)`, then for each section `M.buildMeetings(group, { noRoomPatterns: noRoom.get(group.courseKey), notesExams: true })`.');
  L.push('4. In the `batch.set(..., { merge: true })` payload add `meetings` when the section is undergrad, not OTPMS/MED/LAW and `patternCount >= 2` (match the backfill scope), so single-meeting docs stay unchanged.');
  L.push('5. Top-level fields should then come from `meetings[0]` (or stay as pickPrimaryMeeting) so the two never disagree.');
  L.push('');

  fs.writeFileSync(REPORT_PATH, L.join('\n'));

  console.log(`Plan: ${plan.length} sections, ${kindCount.class} class + ${kindCount.exam} exam meetings, ${perCourse.size} courses`);
  console.log(`  wrote ${PLAN_PATH}`);
  console.log(`  wrote ${REPORT_PATH}`);
  console.log(`  mismatches: ${mismatches.length}, exam-first: ${examFirst.length}, excluded allowlist: ${excludedAllowlist.length}`);
}

main();
