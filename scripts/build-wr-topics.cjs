// Builds src/data/wrTopics.js (WR section topics shown in the scheduler) from two local
// files in scripts/wr-topics-src/. Read-only: no Firestore, no network.
//
// Usage: node scripts/build-wr-topics.cjs [term]      (default 2271)
//   scripts/wr-topics-src/section-topics-<term>.csv   term,course,section,class_nbr,instructor_last,topic,note
//   scripts/wr-topics-src/writing-program-page.txt    text copied from the Writing Program page
'use strict';
const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');
const { normalizeTitle, parseTopicTables, lookupRow } = require('./lib/wrTopicsParse.cjs');

const term = process.argv[2] || '2271';
const srcDir = path.join(__dirname, 'wr-topics-src');
const csv = parse(fs.readFileSync(path.join(srcDir, `section-topics-${term}.csv`), 'utf8'), {
  columns: true,
  skip_empty_lines: true,
  bom: true,
});
const pageText = fs.readFileSync(path.join(srcDir, 'writing-program-page.txt'), 'utf8');
if (!pageText.trim()) throw new Error('writing-program-page.txt is empty');
const rows = parseTopicTables(pageText);

// Titles whose descriptions differ by instructor (e.g. The Theater Now) get one topic per
// instructor; everything else shares one topic per title.
const descsByKey = new Map();
for (const r of rows) {
  if (!descsByKey.has(r.key)) descsByKey.set(r.key, new Set());
  descsByKey.get(r.key).add(r.description);
}

const sections = {};
const topics = {};
const usedRows = new Set();
const noDescription = new Set();
const ambiguous = [];
let noTopic = 0;

for (const c of csv) {
  const title = (c.topic || '').trim();
  if (!title) { noTopic += 1; continue; }
  const base = normalizeTitle(title);
  const hit = lookupRow(rows, title, c.instructor_last);
  let key = base;
  let entry;
  if (hit) {
    usedRows.add(hit.row);
    if (hit.how === 'instructor (ambiguous)') ambiguous.push(`${c.class_nbr} ${title} / ${c.instructor_last}`);
    if (descsByKey.get(base).size > 1) key = `${base}~${normalizeTitle(hit.row.instructor)}`;
    // Second Wave Feminism's page text is SIS boilerplate: keep the title only.
    const description = base === 'second wave feminism to now' ? '' : hit.row.description;
    entry = { title: hit.row.title, description };
  } else {
    noDescription.add(title);
    entry = { title, description: '' };
  }
  sections[String(c.class_nbr)] = key;
  topics[key] = entry;
}

const header = `// WR section topics for Spring 2027 (term ${term}), shown on scheduler sections.
// Generated by scripts/build-wr-topics.cjs: don't edit by hand.
//   sections: classNbr -> topic key.  topics: topic key -> { title, description }.
// Only applied when section.term matches \`term\` (see src/utils/wrTopics.js), so it does
// nothing once CURRENT_TERM moves on.
//
// REFRESH EACH TERM:
//   1. Put the term's section/topic CSV in scripts/wr-topics-src/section-topics-<term>.csv
//      (term,course,section,class_nbr,instructor_last,topic,note; blank topic = none).
//   2. Paste the Writing Program page text into scripts/wr-topics-src/writing-program-page.txt
//      (it needs the "WR 120 Topics (...)" and "WR 151, WR 152, and WR 153 Topics (...)" tables).
//   3. node scripts/build-wr-topics.cjs <term>   (read-only, local files) and read its report:
//      topics with no description, page topics no section uses, sections with no topic.
//   4. node --test scripts/lib/wrTopicsParse.test.js
`;
const out = `${header}\nexport const wrTopics = ${JSON.stringify({ term, sections, topics }, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'wrTopics.js'), out);

const unusedPage = rows.filter((r) => !usedRows.has(r)).map((r) => `${r.title} (${r.instructor}, ${r.wr})`);
console.log(`page rows: ${rows.length}, CSV rows: ${csv.length}`);
console.log(`sections with a topic: ${Object.keys(sections).length}, topics: ${Object.keys(topics).length}`);
console.log(`CSV topics with no description match (${noDescription.size}):`, [...noDescription]);
console.log(`page topics unused by any section (${unusedPage.length}):`, unusedPage);
console.log(`ambiguous surname matches (${ambiguous.length}):`, ambiguous);
console.log(`sections with no topic: ${noTopic}`);
